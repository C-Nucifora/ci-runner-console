// In an isolated browser fixture page: (await import('/__regression.js')).run()
export async function run() {
  const passed = [];
  const check = (condition, message) => { if (!condition) throw new Error(message); passed.push(message); };
  const wait = async (fn) => {
    for (let i = 0; i < 100; i++) {
      if (fn()) return;
      await new Promise(resolve => setTimeout(resolve, 20));
    }
    throw new Error('Timed out waiting for browser state');
  };
  const button = (text, root = document) => [...root.querySelectorAll('button')].find(b => b.textContent.trim() === text);
  const fill = (id, value) => {
    const input = document.getElementById(id);
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, value);
    input.dispatchEvent(new Event('input', { bubbles: true }));
  };
  const f = window.fixture;
  await wait(() => button('Add runner'));
  const luminance = (color) => {
    const values = color.match(/[\d.]+/g).slice(0, 3).map(Number).map(v => {
      v /= 255;
      return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
    });
    return values[0] * 0.2126 + values[1] * 0.7152 + values[2] * 0.0722;
  };
  const contrast = (element, background = element) => {
    const foreground = luminance(getComputedStyle(element).color);
    const behind = luminance(getComputedStyle(background).backgroundColor);
    return (Math.max(foreground, behind) + 0.05) / (Math.min(foreground, behind) + 0.05);
  };
  check(contrast(button('Add runner')) >= 4.5, 'primary button text meets 4.5 to 1 contrast');
  const unit = document.querySelector('.unit');
  check(contrast(unit, unit.closest('article')) >= 4.5, 'runner service text meets 4.5 to 1 contrast');
  check(contrast(document.querySelector('button.danger')) >= 4.5, 'destructive action text meets 4.5 to 1 contrast');
  const automatic = document.querySelector('.chip[data-auto="true"]');
  check(contrast(automatic) >= 4.5 && getComputedStyle(automatic).opacity === '1', 'automatic label text meets 4.5 to 1 contrast');
  const cards = [...document.querySelectorAll('article.runner')];
  check(!cards.find(c => c.textContent.includes('busy-instance')).textContent.includes('Delete'), 'busy job has no destructive controls');
  check(!cards.find(c => c.textContent.includes('protected-instance')).querySelector('button'), 'protected runner has no controls');
  button('Add runner').click();
  await wait(() => document.querySelector('dialog[open]'));
  const dialog = document.querySelector('dialog');
  check(document.getElementById(dialog.getAttribute('aria-labelledby')).textContent === 'Add a runner', 'create dialog has accessible name');
  check(document.activeElement.id === 'rname', 'create dialog focuses name');
  check([...dialog.querySelectorAll('input')].every(input => input.labels.length > 0), 'create fields have associated labels');
  fill('rname', 'invalid name');
  await wait(() => document.getElementById('rname').getAttribute('aria-invalid') === 'true');
  check(button('Add runner', dialog).disabled && document.getElementById('rname-hint').textContent.includes('Use letters'), 'invalid name explains allowed characters and blocks submission');
  fill('rname', 'idle-instance');
  await wait(() => document.getElementById('rname-hint').textContent.includes('already exists'));
  check(button('Add runner', dialog).disabled, 'duplicate name blocks submission');
  fill('rname', 'synthetic-new'); fill('rlabels', 'gpu, large');
  await wait(() => !button('Add runner', dialog).disabled);
  f.pending = true;
  button('Add runner', dialog).click();
  await wait(() => f.release);
  check(button('Creating…', dialog).disabled, 'create action disables repeated submissions');
  check([...dialog.querySelectorAll('input, button')].every(control => control.disabled), 'pending create locks inputs and cancel');
  dialog.querySelector('form').requestSubmit();
  check(f.requests.filter(r => r.path === '/api/runners' && r.method === 'POST').length === 1, 'pending create ignores repeated form submissions');
  const cancel = new Event('cancel', { cancelable: true });
  dialog.dispatchEvent(cancel);
  check(cancel.defaultPrevented && dialog.open, 'cancel during submission keeps dialog open');
  f.release(); f.pending = false;
  await wait(() => dialog.textContent.includes('Synthetic create rejected'));
  check(dialog.open && document.getElementById('rname').value === 'synthetic-new' && document.getElementById('rlabels').value === 'gpu, large', 'create failure keeps inputs and shows error inside dialog');
  check(dialog.querySelector('[role="alert"]').textContent.includes('Refresh inventory and choose a unique name.'), 'create recovery hint is accessible inside modal');
  f.malformed = true;
  button('Add runner', dialog).click();
  await wait(() => dialog.textContent.includes('Invalid server response (502)'));
  check(!dialog.textContent.includes('Unexpected token'), 'malformed JSON gives actionable error');
  f.inventory.cap.canCreate = false; f.poll();
  await wait(() => button('Add runner', dialog).disabled);
  check(button('Add runner', dialog).disabled, 'open create dialog respects changed capacity');
  f.inventory.cap.canCreate = true; f.inventoryFailure = true; f.poll();
  await wait(() => document.body.textContent.includes('Cannot load runner state'));
  check([...document.querySelectorAll('article.runner button')].every(b => b.disabled) && button('Add runner').disabled, 'failed refresh disables stale inventory controls');
  check(button('Add runner', dialog).disabled && dialog.textContent.includes('Refresh runner state'), 'open create dialog blocks submission on stale inventory');
  button('Cancel', dialog).click();
  f.inventoryFailure = false; button('Retry').click();
  await wait(() => !button('Add runner').disabled);
  check(!button('Restart').disabled, 'successful retry restores controls');
  f.pending = true; f.release = null; button('Restart').click();
  await wait(() => f.release && button('Restart').disabled);
  check(button('Add runner').disabled && button('Sign out').disabled, 'pending runner action locks conflicting actions');
  f.release(); f.pending = false;
  await wait(() => !button('Restart').disabled);
  button('Logs').click();
  await wait(() => document.querySelector('dialog[open]'));
  const log = document.querySelector('dialog');
  check(document.getElementById(log.getAttribute('aria-labelledby')).textContent === 'busy-instance', 'logs dialog has accessible name');
  button('Close', log).click();
  f.pending = true; f.release = null; button('Sign out').click();
  await wait(() => f.release);
  check(button('Signing out…').disabled, 'pending logout disables repeated submissions');
  check(button('Add runner').disabled && [...document.querySelectorAll('article.runner button')].every(b => b.disabled), 'pending logout locks runner controls');
  f.release(); f.pending = false;
  await wait(() => button('Sign out') && !button('Sign out').disabled);
  check(document.body.textContent.includes('Synthetic logout unavailable'), 'logout failure shows error and permits retry');
  f.malformed = false; f.createFailure = false;
  button('Add runner').click();
  await wait(() => document.querySelector('dialog[open]'));
  fill('rname', 'synthetic-success');
  await wait(() => !button('Add runner', document.querySelector('dialog')).disabled);
  button('Add runner', document.querySelector('dialog')).click();
  await wait(() => !document.querySelector('dialog[open]'));
  check(document.body.textContent.includes('synthetic-success is registered and online in GitHub.'), 'successful create closes dialog and confirms registration');
  button('Settings').click();
  await wait(() => document.body.textContent.includes('Synthetic configuration'));
  check(document.documentElement.scrollWidth <= innerWidth, `settings has no horizontal overflow at ${innerWidth}px`);
  await wait(() => button('Re-check')?.disabled === false);
  f.healthFailure = true; button('Re-check').click();
  await wait(() => document.body.textContent.includes('Request failed (503)') && button('Re-check')?.disabled === false);
  check(document.body.textContent.includes('Request failed (503)'), 'health failure reported with retry available');
  button('Runners').click();
  await wait(() => button('Add runner'));
  check(document.documentElement.scrollWidth <= innerWidth, `runners has no horizontal overflow at ${innerWidth}px`);
  button('Settings').click();
  await wait(() => document.body.textContent.includes('Checks unavailable. Use Re-check to retry.'));
  check(!document.body.textContent.includes('Running checks…'), 'failed initial health check stops loading indicator');
  check(f.requests.filter(r => r.path === '/api/runners' && r.method === 'POST').length === 3, 'exactly three synthetic create attempts');
  return { passed, requests: f.requests.length, viewport: { width: innerWidth, height: innerHeight } };
}
